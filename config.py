# -*- coding: utf-8 -*-
"""
参数配置文件
============================================================
论文: Tang et al., "Collaborative Service Caching, Task Offloading,
      and Resource Allocation in Caching-Assisted Mobile Edge
      Computing", IEEE TSC, 2025.

本文件将所有仿真参数集中管理，并明确标注:
    [论文]   -- 由论文 Section VII-A (Experimental Setups) 明确给出
    [假设]   -- 论文未给出、为保持可复现性而采用的合理取值

所有物理量单位约定:
    数据量 d_n        : bit   (论文以 MB 给出, 内部统一转 bit)
    计算量 s_n        : cycle (论文以 GHz 给出, 理解为 Giga-cycle = 1e9 cycle)
    频率 f, F_e       : Hz    (GHz = 1e9 Hz)
    带宽 b_n, W       : Hz    (论文以 GHz 给出)
    时间              : s
    能量              : J
    存储 h_k, C       : GB
"""
import numpy as np


class Config:
    # ============================================================
    # 一、场景规模 [论文]
    # ============================================================
    N = 30                 # 用户设备(UD)数量, 默认 30 (Fig.7/8); 9 用 10~40, Fig.10 用 20
    K = 10                 # 服务数量 [论文: 10 services]
    T_train = 20000        # 训练时隙数 [论文: 约 20000 步收敛]
    T_test = 10000         # 测试时隙数 [论文: 10000 time slots]
    T_max = 20000          # 每 episode 最大时隙(训练用)

    # ============================================================
    # 二、任务特征分布 [论文]
    # ============================================================
    d_min, d_max = 1.0, 6.0            # 输入数据大小 U(1,6) MB
    s_min, s_max = 1.0, 5.0            # CPU 需求 U(1,5) GHz(按 Giga-cycle 理解)
    lmax_min, lmax_max = 0.7, 3.0      # 任务截止时间 U(0.7,3) 秒

    # ============================================================
    # 三、服务特征 [论文]
    # ============================================================
    h_min, h_max = 1.0, 4.0            # 服务存储需求 U(1,4) GB
    gamma_min, gamma_max = 2.0, 5.0    # 缓存每个服务每时隙静态能耗 U(2,5)

    # ============================================================
    # 四、边缘服务器(ES)能力 [论文]
    # ============================================================
    C = 10.0               # ES 存储容量 10 GB
    F_e = 40e9             # ES 总计算资源 40 GHz
    W = 30e9               # 上行总带宽 30 GHz

    # ============================================================
    # 五、服务请求转移模型 [论文: 均匀转移]
    # ============================================================
    # 给定上一时隙请求服务 i, 当前请求服务 k 的概率服从均匀分布
    request_stickiness = 0.0   # 0 表示纯均匀; >0 表示以该概率保持请求同一服务

    # ============================================================
    # 六、几何与信道 [论文: 100x100 区域, BS 居中, UD 均匀分布]
    # ============================================================
    area_size = 100.0      # 区域边长 [论文]
    # ---- 以下为信道模型具体化 [假设] ----
    alpha = 3.0            # 大尺度路径损耗指数 g = d^{-alpha}
    fading = True          # 是否加入 Rayleigh 快衰落
    N0 = 1e-19             # 噪声功率谱密度 (W/Hz) [假设]
    p_n = 0.1              # UD 发射功率 (W) [假设]
    ref_gain = 1.0         # 信道参考增益 [假设]

    # ============================================================
    # 七、本地计算 [假设: 论文未给本地频率分布]
    # ============================================================
    f_local = 2.0e9        # 本地 CPU 频率 2 GHz (Hz)
    # 说明: 取 2GHz 使 N=30 时约 65% 任务本地可满足, 其余须卸载后合计约
    #       31.5 Gcycle < F_e=40 Gcycle, 即 ES 紧而不爆, 缓存/卸载决策才有区分度。
    #       若取 1GHz, 则 l_local = s 均值 3s 远超 lmax 均值 1.85s, 本地可行率仅
    #       21.7%, 系统过载 -> 所有算法满意度均为负且无区分度。

    # ============================================================
    # 八、云下载与能耗 [假设]
    # ============================================================
    r_cloud = 5.0          # ES 与远端云之间下载速率 (GB/s, 约 40 Gbps), 用于服务下载时延 [假设]
    response_cap = 10.0    # 响应时间指标上限(s): 错过截止时间的任务按此封顶统计 [假设]
    k_e = 1e-27            # ES 有效开关电容系数 [假设]
    Q = 2000.0             # ES 单时隙能量预算 (J), 设宽松使能量约束非主导 [假设]

    # ============================================================
    # 九、满意度函数 [论文 Eq.(9)]
    # ============================================================
    phi = 0.0              # 满意度标定参数, 保证对数自变量非负 [论文, 数值未给]
    eps = 1e-9             # 数值下限, 防止 log(0)/NaN

    # ============================================================
    # 十、A2C 网络与训练超参数 [假设: 论文未给具体数值]
    # ============================================================
    hidden = [128, 128]    # 隐层维度
    lr_actor = 1e-3        # 缓存 actor 学习率
    lr_critic = 1e-3       # 缓存 critic 学习率
    lr_off = 1e-3          # 卸载网络学习率
    gamma = 0.99           # 折扣因子
    Mca = 1000             # 缓存模块经验回放容量
    Moff = 1000            # 卸载模块经验回放容量
    batch = 64             # 采样批大小
    seed = 0               # 随机种子

    # ============================================================
    # 十一、资源分配算法容差与迭代 [论文 Algorithm 1/2]
    # ============================================================
    tol_b = 1e-3           # 内层二分 b 容差(相对)
    tol_theta = 1e-3       # 外层二分 theta 容差(相对)
    max_iter_bra = 200     # BRA 外层最大迭代
    # 注: CRA 采用二分 Lagrange 乘子 omega + 能量投影求解(见 resource_alloc.py), 无需步长参数

    # ============================================================
    # 十二、卸载量化 [论文 VI-B1: order-preserving quantization]
    # ============================================================
    M_off = None           # 候选卸载动作数; None 表示 = N

    # ============================================================
    # 十三、实验控制
    # ============================================================
    quick = False          # True 时用极小规模跑通流程(smoke test)
    device = 'cpu'
    moving_avg_window = 500

    # ------------------------------------------------------------
    def __post_init__(self):
        self.d_min_b = self.d_min * 1e6 * 8
        self.d_max_b = self.d_max * 1e6 * 8
        self.s_min_c = self.s_min * 1e9   # cycle
        self.s_max_c = self.s_max * 1e9
        if self.M_off is None:
            self.M_off = self.N
        if self.quick:
            self.N = 8
            self.K = 4
            self.T_train = 200
            self.T_test = 200
            self.Mca = 200
            self.Moff = 200
            self.batch = 16
            self.max_iter_bra = 40
            self.hidden = [32, 32]
            self.M_off = self.N


def make_config(**overrides) -> Config:
    """创建配置对象, 支持命令行覆盖。"""
    cfg = Config()
    for k, v in overrides.items():
        if hasattr(cfg, k):
            setattr(cfg, k, v)
    cfg.__post_init__()
    return cfg
